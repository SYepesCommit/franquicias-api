package com.example.sucursal.model;

public class Franquicia {

    private String id;
    private String nombre;

    public Franquicia() {
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

}

